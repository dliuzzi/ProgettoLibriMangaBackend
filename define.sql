
    create table autori (
        id integer generated by default as identity,
        cognome varchar(30) not null,
        nome varchar(30) not null,
        primary key (id)
    );

    create table case_editrici (
        id integer generated by default as identity,
        nome varchar(100) not null,
        sede varchar(100),
        primary key (id)
    );

    create table categorie (
        id integer generated by default as identity,
        categoria varchar(50) not null,
        primary key (id)
    );

    create table dettagli_carrelli (
        id integer generated by default as identity,
        id_libro integer not null,
        id_utente integer not null,
        quantita integer not null,
        primary key (id)
    );

    create table dettagli_ordini (
        costo_totale float(53) not null,
        data DATE not null,
        id integer generated by default as identity,
        id_libro integer,
        id_ordine integer,
        quantita integer not null,
        stato smallint not null check ((stato between 0 and 2)),
        primary key (id)
    );

    create table libri (
        data_pubblicazione DATE not null,
        id integer generated by default as identity,
        id_autore integer,
        id_casa_editrice integer,
        prezzo float(53) not null,
        quantita_disponibile integer not null,
        titolo varchar(100) not null,
        copertina varchar(255),
        descrizione TEXT,
        primary key (id)
    );

    create table libri_categorie (
        id_categoria integer not null,
        id_libro integer not null,
        primary key (id_categoria, id_libro)
    );

    create table libri_preferiti (
        id_libro integer not null,
        id_utente integer not null,
        primary key (id_libro, id_utente)
    );

    create table messaggi_sistema (
        lang varchar(4) not null,
        code varchar(20) not null,
        messaggio varchar(255),
        primary key (lang, code)
    );

    create table ordini (
        id integer generated by default as identity,
        id_utente integer not null,
        primary key (id)
    );

    create table recensioni (
        data DATE not null,
        id integer generated by default as identity,
        id_libro integer,
        id_utente integer,
        stelle integer not null,
        contenuto varchar(255),
        primary key (id)
    );

    create table utenti (
        id integer generated by default as identity,
        ruolo smallint not null check ((ruolo between 0 and 1)),
        cognome varchar(30) not null,
        nome varchar(30) not null,
        email varchar(100) not null unique,
        provincia varchar(100),
        telefono varchar(100),
        via varchar(100),
        immagine_profilo varchar(255),
        password varchar(255) not null,
        primary key (id)
    );

