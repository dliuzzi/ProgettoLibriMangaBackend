
    create table autori (
        id integer generated by default as identity,
        cognome varchar(30) not null,
        nome varchar(30) not null,
        primary key (id)
    );

    create table case_editrici (
        id integer generated by default as identity,
        sede varchar(100) not null,
        primary key (id)
    );

    create table categorie (
        id integer generated by default as identity,
        categoria varchar(50) not null,
        primary key (id)
    );

    create table libri (
        data_pubblicazione DATE not null,
        id integer generated by default as identity,
        id_autore integer,
        id_casa_editrice integer,
        prezzo float(53) not null,
        copertina varchar(100),
        titolo varchar(100) not null,
        descrizione varchar(500),
        primary key (id)
    );

    create table libri_categorie (
        id_categoria integer not null,
        id_libro integer not null,
        primary key (id_categoria, id_libro)
    );

    create table messaggi_sistema (
        lang varchar(4) not null,
        code varchar(20) not null,
        messaggio varchar(255),
        primary key (lang, code)
    );

    create table utenti (
        id integer generated by default as identity,
        cognome varchar(30) not null,
        nome varchar(30) not null,
        password varchar(30) not null,
        email varchar(100) not null unique,
        primary key (id)
    );

